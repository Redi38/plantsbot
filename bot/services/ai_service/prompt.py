_MAX_PLANTS_IN_PROMPT = 300


def select_relevant_plants(user_text: str, existing_plants: list[str], limit: int) -> list[str]:
    """Обрезка списка растений в промпте, когда их больше limit — включает
    в первую очередь названия, буквально пересекающиеся с текстом запроса.

    ВАЖНО: это сравнение буквальное и работает только в рамках одного
    алфавита (см. bot/utils/fuzzy.fuzzy_find с той же оговоркой). Если
    запрос на кириллице, а названия растений латиницей (или наоборот),
    "relevant" почти наверняка окажется пустым, и в промпт попадут
    произвольные первые limit растений — включая, возможно, ни одного
    нужного. Модель после этого физически не может сопоставить то, чего
    не видела, сколько бы кроссязыковых инструкций ни было в system-
    prompt. Поэтому limit стоит держать заметно больше реального размера
    коллекции пользователей — тогда обрезка вообще не включается и этот
    нюанс не имеет значения. Если коллекции всё же вырастут настолько, что
    limit придётся снижать — сначала почини сам подбор relevant (например,
    сравнивать транслитерацию или сначала спросить модель, какие названия
    вообще могут быть релевантны), иначе баг вернётся."""
    if len(existing_plants) <= limit:
        return existing_plants

    text_lower = user_text.lower()
    text_words = [w for w in re.findall(r"[a-zа-яё]{3,}", text_lower)]

    relevant: list[str] = []
    rest: list[str] = []
    for name in existing_plants:
        name_lower = name.lower()
        is_relevant = name_lower in text_lower or any(word in name_lower for word in text_words)
        (relevant if is_relevant else rest).append(name)

    result = relevant[:limit]
    if len(result) < limit:
        result += rest[: limit - len(result)]
    return result


def build_system_prompt(
    existing_groups: list[str] | None,
    existing_plants: list[str] | None,
    existing_zones: list[str] | None = None,
) -> str:
    if existing_groups:
        groups_block = _GROUPS_BLOCK_TEMPLATE.format(groups_list=", ".join(f"«{g}»" for g in existing_groups))
    else:
        groups_block = _NO_GROUPS_BLOCK
    if existing_plants:
        plants_block = _PLANTS_BLOCK_TEMPLATE.format(plants_list=", ".join(f"«{p}»" for p in existing_plants))
    else:
        plants_block = _NO_PLANTS_BLOCK
    if existing_zones:
        zones_block = _ZONES_BLOCK_TEMPLATE.format(zones_list=", ".join(f"«{z}»" for z in existing_zones))
    else:
        zones_block = _NO_ZONES_BLOCK
    return SYSTEM_PROMPT_TEMPLATE.format(groups_block=groups_block, plants_block=plants_block, zones_block=zones_block)
